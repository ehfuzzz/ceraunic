"""Helpers for scripts/phase3_repull.sh. Reads files only; writes nothing except the --tsv you name.

  phase3_repull_diff.py diff OLD.json NEW.json [--tsv PATH]
      every leaf of results.json that changed (old -> new); the headline metrics are printed, the rest goes to the TSV
  phase3_repull_diff.py handwritten [OLD.json [NEW.json]]
      file:line of every hand-written pair count / 'no PRISM cell' sentence / old headline number in the shipped text
      (reports, decks, memo, walkthrough, eval-03 prose) and in the generators that write them
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKIP = {"meta.written_utc", "meta.command"}
TOL = 5e-7  # results.json is rounded to 6 decimals

# ---------------------------------------------------------------- diff


def flat(x, p: str = "") -> dict:
    out = {}
    if isinstance(x, dict):
        for k, v in x.items():
            out.update(flat(v, f"{p}.{k}" if p else str(k)))
    elif isinstance(x, list):
        for i, v in enumerate(x):
            out.update(flat(v, f"{p}[{i}]"))
    else:
        out[p] = x
    return out


def _num(v) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def changed_leaves(old: dict, new: dict) -> list[tuple[str, object, object]]:
    a, b = flat(old), flat(new)
    out = []
    for k in sorted(set(a) | set(b)):
        if k in SKIP:
            continue
        x, y = a.get(k, "<absent>"), b.get(k, "<absent>")
        if _num(x) and _num(y):
            if abs(x - y) > TOL:
                out.append((k, x, y))
        elif x != y:
            out.append((k, x, y))
    return out


HEAD_METRICS = ("n_pairs", "pooled_median_he", "pooled_median_dhe", "dhe_ci", "pooled_median_eta", "share_pairs_dhe_pos",
                "markets_dhe_pos", "verdict", "rule_outcome", "P1", "P2", "P3")


def is_headline(path: str) -> bool:
    if path.startswith(("verdicts.", "counts.", "cells.prism_cell", "bakeoff_matched_prism_pairs._")):
        return True
    if path.startswith("eval02.") and ".by_market." not in path and not path.startswith(("eval02.points", "eval02.extras")):
        return True
    m = re.match(r"bakeoff(_matched_prism_pairs)?\.(temperature|rain)\.[^.]+\.(\w+)", path)
    if m:
        return m.group(3) in HEAD_METRICS
    m = re.match(r"bakeoff_matched_prism_pairs\.(temperature|rain)\._paired_he_diff_vs_G1-P", path)
    return bool(m)


def fmt(v) -> str:
    if isinstance(v, float):
        return f"{v:.3f}"
    return str(v)[:60]


def cmd_diff(old_p: str, new_p: str, tsv: str | None) -> int:
    old, new = json.loads(Path(old_p).read_text()), json.loads(Path(new_p).read_text())
    ch = changed_leaves(old, new)
    head = [c for c in ch if is_headline(c[0])]
    print(f"results.json: {len(ch)} leaves changed ({len(head)} headline, printed below; all of them in the TSV)")
    w = max([len(c[0]) for c in head] + [10])
    print(f"{'key':<{w}}  {'old':>14}  ->  {'new':<14}")
    for k, x, y in head:
        print(f"{k:<{w}}  {fmt(x):>14}  ->  {fmt(y):<14}")
    if tsv:
        Path(tsv).parent.mkdir(parents=True, exist_ok=True)
        with open(tsv, "w") as f:
            f.write("key\told\tnew\n")
            for k, x, y in ch:
                f.write(f"{k}\t{x}\t{y}\n")
        print("full list:", tsv)
    return 0


