COUNT_PATTERNS = [
    ("pair count", r"\b\d+ of \d+ (?:station |rain |temperature |truth )?pairs?\b"),
    ("pair count", r"\b\d+/\d+ (?:station |rain |temperature )?pairs?\b"),
    ("pair count", r"\b(?:on|of|over|across|for) (?:the )?(?:same )?\d+(?: station| rain| temperature)? pairs?\b"),
    ("pair count", r"\b\d+ (?:station |rain |temperature |truth )?pairs\b"),
    ("pair count", r"\b(?:same|those|these) (?:19|26|27|37)\b"),
    ("pair count", r"\bn_pairs`? = \d+"),
    ("pair count", r"\b(?:7|10) pairs\b|\bthe other 7\b|\bother 7\b"),
    ("no-PRISM-cell sentence", r"no PRISM cell|PRISM cell (?:was|were) (?:not )?(?:pulled|kept)|without a PRISM cell|fewer pairs"),
    ("deviation 1", r"\b[Dd]eviation 1\b|9 points"),
]


def headline_numbers(old: dict, new: dict | None) -> list[tuple[str, float]]:
    """(label, value) of the old G1-P / P-A-IDW / R-A / G1-N headline numbers that move (or all, if no new file)."""
    a = flat(old)
    b = flat(new) if new else None
    keys = []
    for var in ("temperature", "rain"):
        for d in ("G1-P", "P-A-IDW", "R-A", "G1-N"):
            for m in ("pooled_median_dhe", "pooled_median_he", "pooled_median_eta", "dhe_ci[0]", "dhe_ci[1]", "he_ci[0]", "he_ci[1]"):
                keys.append(f"bakeoff.{var}.{d}.{m}")
        for d in ("R-A", "P-A-IDW", "G1-N"):
            for m in ("he_diff", "ci[0]", "ci[1]"):
                keys.append(f"bakeoff_matched_prism_pairs.{var}._paired_he_diff_vs_G1-P.{d}.{m}")
        for m in ("pooled_median_he", "pooled_median_dhe", "pooled_median_eta", "dhe_ci[0]", "dhe_ci[1]"):
            keys.append(f"bakeoff_matched_prism_pairs.{var}.G1-P.{m}")
        for m in ("he_diff", "ci[0]", "ci[1]"):
            keys.append(f"verdicts.winner_vs_runner_up.{var}.{m}")
    for m in ("he_diff", "ci[0]", "ci[1]"):
        keys.append(f"verdicts.winner_vs_next_survivor.rain.{m}")
    keys += ["verdicts.pc1_vs_equal.he_diff", "verdicts.pc1_vs_equal.ci[0]", "verdicts.pc1_vs_equal.ci[1]"]
    out = []
    for k in keys:
        x = a.get(k)
        if not _num(x) or abs(x) < 0.05:
            continue
        if b is not None and _num(b.get(k)) and abs(b[k] - x) <= TOL:
            continue
        out.append((k, float(x)))
    return out


def cmd_handwritten(old_p: str | None, new_p: str | None) -> int:
    old = json.loads(Path(old_p or ROOT / "reports/eval-03/results.json").read_text())
    new = json.loads(Path(new_p).read_text()) if new_p else None
    pats = [(tag, re.compile(rx)) for tag, rx in COUNT_PATTERNS]
    nums = []
    seen = set()
    for k, v in headline_numbers(old, new):
        for dp, conf in ((3, "old value"),):
            s = f"{abs(v):.{dp}f}"
            s = s[1:] if s.startswith("0") else s  # ".186"
            if (s, dp) in seen:
                continue
            seen.add((s, dp))
            nums.append((f"number {'0' + s} [{k}]", re.compile(r"(?<![\d.])0?" + re.escape(s) + r"(?!\d)")))

    def scan(rel: str, note: str) -> int:
        p = ROOT / rel
        if not p.exists():
            return 0
        n = 0
        use_nums = not note.startswith("generated")  # generated files take their numbers from keys
        for i, line in enumerate(p.read_text(errors="replace").splitlines(), 1):
            tags = []
            for tag, rx in pats:
                if rx.search(line) and tag not in tags:
                    tags.append(tag)
            for tag, rx in (nums if use_nums else []):
                if rx.search(line):
                    tags.append(tag)
            if tags:
                n += 1
                if len(tags) > 4:
                    tags = tags[:4] + [f"+{len(tags) - 4} more numbers"]
                print(f"{rel}:{i}: [{'; '.join(tags)}] {line.strip()[:170]}")
        return n

    total = 0
    print("# shipped text and generators (fix in the source; generated files follow `make report` / build_decks.py)")
    for rel, note in SHIPPED:
        c = scan(rel, note)
        print(f"# {rel}: {c} line(s) ({note})")
        total += c
    print("# planning docs (status text, not shipped)")
    for rel in PLANNING:
        c = scan(rel, "planning")
        print(f"# {rel}: {c} line(s)")
        total += c
    print(f"# total {total} hit lines. Pair counts of 37 / 26 for eval02 (station leg alone) stay correct: they do not depend on PRISM.")
    return 0


def main(argv: list[str]) -> int:
    if len(argv) >= 4 and argv[1] == "diff":
        tsv = argv[argv.index("--tsv") + 1] if "--tsv" in argv else None
        return cmd_diff(argv[2], argv[3], tsv)
    if len(argv) >= 2 and argv[1] == "handwritten":
        rest = [a for a in argv[2:] if not a.startswith("--")]
        return cmd_handwritten(rest[0] if rest else None, rest[1] if len(rest) > 1 else None)
    print(__doc__)
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
